const excludedPathParts = new Set([
  ".git",
  "node_modules",
  "dist",
  "build",
  "coverage",
  ".cache",
  ".turbo",
  ".natt-memory",
  "history",
]);

const excludedNames = new Set([
  ".env",
  ".env.local",
  "last-offensive-run.json",
  "discord_backup_codes.txt",
]);

function toPosix(path) {
  return path.replace(/\\/g, "/");
}

function isWithin(parent, child) {
  const relativePath = relative(parent, child);
  return (
    relativePath === "" ||
    (!relativePath.startsWith("..") &&
      !resolve(relativePath).startsWith("\\\\"))
  );
}

function shouldExclude(absPath) {
  const rel = toPosix(relative(root, absPath));
  const parts = rel.split("/");
  if (parts.some((part) => excludedPathParts.has(part))) return true;
  const name = parts.at(-1) ?? "";
  if (excludedNames.has(name)) return true;
  if (name.endsWith(".log") || name.endsWith(".tmp")) return true;
  if (name.startsWith(".env.")) return true;
  return false;
}

function copyPath(inputPath) {
  const src = resolve(root, inputPath);
  if (!isWithin(root, src)) {
    throw new Error(`Refusing to copy path outside repo: ${inputPath}`);
  }
  if (!existsSync(src)) {
    return { path: inputPath, copied: false, reason: "missing" };
  }
  if (shouldExclude(src)) {
    return { path: inputPath, copied: false, reason: "excluded" };
  }

  const dest = join(sourceRoot, inputPath);
  mkdirSync(dirname(dest), { recursive: true });
  cpSync(src, dest, {
    recursive: true,
    filter: (candidate) => !shouldExclude(candidate),
  });
  return { path: inputPath, copied: true };
}

function sha256(absPath) {
  return createHash("sha256").update(readFileSync(absPath)).digest("hex");
}

function collectFiles(absDir) {
  if (!existsSync(absDir)) return [];
  const entries = [];
  for (const entry of readdirSync(absDir)) {
    const absPath = join(absDir, entry);
    const stat = statSync(absPath);
    if (stat.isDirectory()) {
      entries.push(...collectFiles(absPath));
    } else if (stat.isFile()) {
      entries.push(absPath);
    }
  }
  return entries;
}

function writeReadme() {
  const readme = `# NATT Offline Vendor Bundle

This directory is generated by \`npm run natt:offline:vendor\`.

It vendors the local DevBot/NATT source surfaces needed for authorized offline operation:

- NATT MCP knowledge server and tactical dashboard
- NATT roadmap, skills catalog, ROE helpers, and offline docs
- DevBot offensive profile runner
- DevBot pentest, safety, and validation surfaces
- Relevant tests and packaging metadata

This bundle intentionally excludes runtime logs, mission memory, secrets, dependency directories, build outputs, and generated caches.

Third-party tools such as Nmap, OWASP ZAP, Burp Suite, Nuclei, Metasploit, Docker images, WSL distributions, and language/package caches must be mirrored separately with pinned versions and license review.
`;
  writeFileSync(join(vendorRoot, "README.md"), readme);
}

function buildManifest(copyResults) {
  const files = collectFiles(sourceRoot).map((absPath) => ({
    path: toPosix(relative(vendorRoot, absPath)),
    bytes: statSync(absPath).size,
    sha256: sha256(absPath),
  }));

  return {
    schemaVersion: "devbot.natt-offline-vendor.v1",
    generatedAt: new Date().toISOString(),
    sourceRepository: "DevBot",
    policy: {
      use: "Authorized, written-ROE security work and offline labs only.",
      excludes: [
        "secrets",
        "runtime logs",
        "mission memory",
        "node_modules",
        "dist/build outputs",
        "generated caches",
      ],
      liveOpsDefault: "dry-run",
    },
    localIncludes: copyResults,
    files,
    recommendedExternalMirrors: [
      {
        name: "vendorpull",
        role: "Pinned git repository vendoring for non-package-manager dependencies.",
        decision:
          "Evaluate only; license metadata needs review before embedding.",
      },
      {
        name: "WSL 2",
        role: "Offline-capable Linux runtime layer for Windows operators.",
        decision:
          "Recommended for Windows NATT labs and POSIX-only vendoring tools.",
      },
      {
        name: "pnpm/npm cache",
        role: "Prime JavaScript dependencies for offline builds.",
        decision:
          "Use lockfiles and local cache exports; do not commit node_modules.",
      },
      {
        name: "Docker save/load",
        role: "Move pinned container images into disconnected environments.",
        decision: "Store checksums and SBOMs beside image archives.",
      },
      {
        name: "apt/offline package mirrors",
        role: "Mirror Linux packages for WSL/Kali/Debian-based lab distros.",
        decision:
          "Keep outside this repo unless small metadata manifests are needed.",
      },
    ],
  };
}

function cleanVendorRoot() {
  const vendorParent = resolve(root, "vendor");
  if (!isWithin(vendorParent, vendorRoot)) {
    throw new Error(`Refusing to clean unexpected path: ${vendorRoot}`);
  }
  rmSync(vendorRoot, { recursive: true, force: true });
  mkdirSync(sourceRoot, { recursive: true });
}

function build() {
  cleanVendorRoot();
  const copyResults = includePaths.map(copyPath);
  writeReadme();
  const manifest = buildManifest(copyResults);
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`NATT offline vendor bundle generated at ${vendorRoot}`);
  console.log(`Files: ${manifest.files.length}`);
}

function check() {
  if (!existsSync(manifestPath)) {
    throw new Error(`Missing manifest: ${manifestPath}`);
  }
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const missing = [];
  const changed = [];
  for (const file of manifest.files ?? []) {
    const absPath = join(vendorRoot, file.path);
    if (!existsSync(absPath)) {
      missing.push(file.path);
      continue;
    }
    const current = sha256(absPath);
    if (current !== file.sha256) {
      changed.push(file.path);
    }
  }
  if (missing.length || changed.length) {
    throw new Error(
      [
        "NATT offline vendor check failed.",
        missing.length ? `Missing: ${missing.join(", ")}` : "",
        changed.length ? `Changed: ${changed.join(", ")}` : "",
      ]
        .filter(Boolean)
        .join("\n"),
    );
  }
  console.log(
    `NATT offline vendor check passed (${manifest.files.length} files).`,
  );
}

const command = process.argv[2] ?? "build";

if (command === "build") {
  build();
} else if (command === "check") {
  check();
} else {
  console.error("Usage: node scripts/natt-offline-vendor.mjs [build|check]");
  process.exitCode = 2;
}
